// Render the shared eligibility cases (tests/fixtures/eligibility-matrix.mjs) as a SQL fixture for suite 73.
//   node scripts/support-eligibility-matrix.mjs          writes supabase/test-fixtures/support-eligibility-matrix.sql
//   node scripts/support-eligibility-matrix.mjs --check  fails if the file is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ELIGIBILITY_CASES } from "../tests/fixtures/eligibility-matrix.mjs";

const target = resolve(dirname(fileURLToPath(import.meta.url)), "../../supabase/test-fixtures/support-eligibility-matrix.sql");

export function renderMatrix(cases = ELIGIBILITY_CASES) {
  const quote = (value) => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
  const rows = cases.map((item) => `(${quote(item.name)}, ${quote(item.input)}, ${quote(item.expected)})`);
  return `-- Generated by my-curated-haven-web/scripts/support-eligibility-matrix.mjs; do not edit by hand.\n`
    + `CREATE TEMP TABLE support_eligibility_matrix(name jsonb, input jsonb, expected jsonb);\n`
    + `INSERT INTO support_eligibility_matrix VALUES\n${rows.join(",\n")};\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rendered = renderMatrix();
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== rendered) { console.error("support-eligibility-matrix.sql is out of date"); process.exitCode = 1; }
  } else {
    writeFileSync(target, rendered);
  }
}
